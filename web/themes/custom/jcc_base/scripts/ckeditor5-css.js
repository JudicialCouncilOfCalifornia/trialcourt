/**
 * @file
 * Builds the stylesheet CKEditor 5 loads through "ckeditor5-stylesheets".
 *
 * CKEditor 4 edited inside an iframe, so the theme CSS listed in
 * "ckeditor_stylesheets" only reached the editor. CKEditor 5 edits in the
 * admin page itself, so the same CSS would restyle the whole admin theme.
 * This scopes every rule to the editable area (.ck-content): html, body and
 * :root become .ck-content, @keyframes and @font-face stay as they are,
 * @import rules move to the top and relative url()s are rewritten for the
 * new location.
 *
 * Usage in webpack.mix.js, after the theme CSS is built:
 *   mix.then(() => require("../jcc_base/scripts/ckeditor5-css")(
 *     ["assets/css/theme.style.css"], "assets/css/ckeditor5.css"));
 * Paths are relative to the theme being built.
 */
const fs = require("fs");
const path = require("path");
const postcss = require("postcss");

const SCOPE = ".ck-content";
const ROOT = /^(?:html|:root)(?=$|[\s.#:[>+~])\s*/;
const BODY = /^body(?=$|[\s.#:[>+~])/;

function scopeSelector(selector) {
  let s = selector.trim();
  if (s.startsWith(SCOPE)) {
    return s;
  }
  s = s.replace(ROOT, "");
  if (s === "" || BODY.test(s)) {
    return SCOPE + s.replace(BODY, "");
  }
  return `${SCOPE} ${s}`;
}

function insideKeyframes(node) {
  for (let parent = node.parent; parent; parent = parent.parent) {
    if (parent.type === "atrule" && /keyframes$/i.test(parent.name)) {
      return true;
    }
  }
  return false;
}

function rewriteUrls(value, from, to) {
  return value.replace(/url\(\s*(['"]?)([^'")]+)\1\s*\)/g, (match, quote, url) => {
    if (/^(?:data:|[a-z]+:|\/|#)/i.test(url)) {
      return match;
    }
    const rel = path.relative(to, path.resolve(from, url)).split(path.sep).join("/");
    return `url(${quote}${rel}${quote})`;
  });
}

module.exports = function buildCkeditor5Css(sources, output) {
  const imports = [];
  const body = [];
  const outDir = path.dirname(path.resolve(output));
  sources.forEach((source) => {
    const file = path.resolve(source);
    const root = postcss.parse(fs.readFileSync(file, "utf8"), { from: file });
    root.walkAtRules("import", (rule) => {
      imports.push(rule.clone());
      rule.remove();
    });
    root.walkRules((rule) => {
      if (!insideKeyframes(rule)) {
        rule.selectors = rule.selectors.map(scopeSelector);
      }
    });
    root.walkDecls((decl) => {
      if (decl.value.includes("url(")) {
        decl.value = rewriteUrls(decl.value, path.dirname(file), outDir);
      }
    });
    body.push(`/* ${path.relative(outDir, file).split(path.sep).join("/")} */\n${root.toString()}`);
  });
  const css = [
    "/* Generated by jcc_base/scripts/ckeditor5-css.js. Do not edit. */",
    ...imports.map((rule) => `${rule.toString()};`),
    ...body,
  ].join("\n");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(output, css);
  console.log(`CKEditor 5 stylesheet: ${output} (${sources.length} sources)`);
};
